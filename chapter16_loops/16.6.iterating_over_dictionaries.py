#-----------------------Example-------------------------
d = {'name':"Tapendra",
     'age':24,
     'phone':9804633911,
     'height':5.9} 





#--------------------To iterate through its keys, you can use:---------------------

for key in d.keys():
    print(key)







#--------------------To iterate through its value, you can use:---------------------  

for value in d.values():
    print(value)  


#--------------------To iterate through its key and values, you can use:---------------------      


for key,value  in d.items():
    print(key," : ",value)


    